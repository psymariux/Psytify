//! Build-time generators for the Kotlin app. [`kotlin_tokens`] writes the design tokens of
//! `psytify-design` as Kotlin constants: the values always come from the Rust constants, so the
//! app never copies a colour or a size by hand. `tests/tokens.rs` fails when the committed file
//! is stale; `cargo run -p psytify-mobile-gen --bin kotlin-tokens` rewrites it, and the sign-in
//! providers' marks ([`brand_vectors`]) with it.

