/// Where the sign-in providers' marks go, as vector drawables (`brand_github.xml`…).
pub const BRANDS_DIR: &str = "android-app/app/src/main/res/drawable";

/// The marks of `psytify_design::brand`: the one vector exception of the design, monochrome, tinted
/// by the app.
const BRANDS: &[(&str, &[u8])] = &[
    ("github", psytify_design::brand::GITHUB),
    ("google", psytify_design::brand::GOOGLE),
    ("discord", psytify_design::brand::DISCORD),
];

/// Each provider's mark as an Android vector drawable: `(file name, XML)`. The Simple Icons sources
/// are one path on a 24 x 24 view box; anything else is an error, not a guess.
pub fn brand_vectors() -> Result<Vec<(String, String)>, String> {
    BRANDS
        .iter()
        .map(|(name, svg)| {
            let svg = std::str::from_utf8(svg).map_err(|_| format!("{name}: not UTF-8"))?;
            if !svg.contains(r#"viewBox="0 0 24 24""#) || svg.matches("<path").count() != 1 {
                return Err(format!("{name}: expected one path on a 24 x 24 view box"));
            }
            let path = svg
                .split(r#" d=""#)
                .nth(1)
                .and_then(|rest| rest.split('"').next())
                .ok_or_else(|| format!("{name}: no path data"))?;
            let xml = format!(
                "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n\
                 <!-- Generated by kotlin-tokens (psytify-mobile-gen) from \
                 design/assets/brands/{name}.svg (Simple Icons, CC0). Do not edit. -->\n\
                 <vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n    \
                 android:width=\"24dp\"\n    android:height=\"24dp\"\n    \
                 android:viewportWidth=\"24\"\n    android:viewportHeight=\"24\">\n    \
                 <path\n        android:fillColor=\"#FFFFFFFF\"\n        android:pathData=\"{path}\" />\n\
                 </vector>\n"
            );
            Ok((format!("brand_{name}.xml"), xml))
        })
        .collect()
}

