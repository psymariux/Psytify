/// The Kotlin source of the tokens and of the sprite metadata. Fails only if the embedded sprite
/// sheet does not load, which is a build bug of `psytify-design`.
pub fn kotlin_tokens() -> Result<String, String> {
    let mut out = String::new();
    out.push_str(
        "// Generated from psytify-design by `cargo run -p psytify-mobile-gen --bin kotlin-tokens`.\n\
         // Do not edit: change the Rust tokens (design/src/tokens) and run the generator again.\n\
         package dev.psytify.app.design\n\n\
         import androidx.compose.ui.graphics.Color\n\
         import androidx.compose.ui.unit.Dp\n\
         import dev.psytify.app.R\n\n",
    );

    out.push_str("/** Palette and semantic colours. Lime marks a state only. */\nobject PsytifyColors {\n");
    for (name, rgba) in COLORS {
        let [r, g, b, a] = rgba.bytes();
        let _ = writeln!(out, "    val {name} = Color(0x{a:02X}{r:02X}{g:02X}{b:02X})");
    }
    out.push_str("}\n\n");

    out.push_str("/** Spacing scale, sizes in dp and art-pixel counts. */\nobject PsytifySpace {\n");
    let _ = writeln!(
        out,
        "    /** One art pixel in nominal dp; on screen it is a whole number of physical pixels. */"
    );
    let _ = writeln!(out, "    const val AP_DP = {}", float(space::AP_DP));
    for (index, value) in space::SCALE.iter().enumerate() {
        let _ = writeln!(out, "    val SPACE_{index} = Dp({})", float(*value));
    }
    for (name, value) in SIZES {
        let _ = writeln!(out, "    val {name} = Dp({})", float(*value));
    }
    out.push_str("    // Shapes in art pixels: each one is `artPx` physical pixels (`PsytifyCore.artPx`).\n");
    for (name, value) in AP {
        let _ = writeln!(out, "    const val {name}_AP = {value}");
    }
    out.push_str("    // Durations in ms.\n");
    for (name, value) in MOTION_MS {
        let _ = writeln!(out, "    const val {name}_MS = {value}");
    }
    out.push_str("}\n\n");

    out.push_str(
        "enum class TypeFamily { UI, PIXEL }\n\n\
         enum class TypeCase { AS_WRITTEN, SENTENCE, UPPER }\n\n\
         /** A type role: size and line height in sp, tracking in px (negative tightens). */\n\
         data class TypeRole(\n    \
             val family: TypeFamily,\n    \
             val size: Float,\n    \
             val lineHeight: Float,\n    \
             val weight: Int,\n    \
             val tracking: Float,\n    \
             val tabular: Boolean,\n    \
             val slashedZero: Boolean,\n    \
             val case: TypeCase,\n\
         )\n\n",
    );
    out.push_str(
        "/** Type roles, with the phone overrides in place of the desktop ones. */\nobject PsytifyType {\n",
    );
    let mut written = Vec::new();
    for (name, role) in PHONE_TYPE.iter().chain(type_::ALL.iter()) {
        if written.contains(name) {
            continue;
        }
        written.push(name);
        let _ = writeln!(out, "    val {name} = {}", role_literal(role));
    }
    out.push_str("}\n\n");

    let sheet = SpriteSheet::load_embedded().map_err(|err| err.to_string())?;
    out.push_str(
        "/**\n * A sprite of `design/assets/pixel/export/1x`: frames side by side, `frameWidth` x `frameHeight` art\n \
         * pixels each, shown for `durationsMs` (0 for a still). A mask is tinted with a colour token.\n */\n\
         data class Sprite(\n    \
             val res: Int,\n    \
             val frameWidth: Int,\n    \
             val frameHeight: Int,\n    \
             val durationsMs: List<Int>,\n    \
             val mask: Boolean,\n\
         )\n\n\
         object PsytifySprites {\n",
    );
    for sprite in sheet.iter() {
        let (width, height) = sprite.frame_size();
        let durations: Vec<String> =
            sprite.frames().iter().map(|frame| frame.duration_ms.to_string()).collect();
        let _ = writeln!(
            out,
            "    val {} = Sprite(R.drawable.{}, {width}, {height}, listOf({}), {})",
            sprite.name().to_uppercase(),
            sprite.name(),
            durations.join(", "),
            sprite.kind() == SpriteKind::Mask,
        );
    }
    out.push_str("}\n");
    Ok(out)
}

fn role_literal(role: &TypeRole) -> String {
    let family = if role.family == type_::FAMILY_PIXEL { "TypeFamily.PIXEL" } else { "TypeFamily.UI" };
    let case = match role.case {
        TextCase::AsWritten => "TypeCase.AS_WRITTEN",
        TextCase::Sentence => "TypeCase.SENTENCE",
        TextCase::Upper => "TypeCase.UPPER",
    };
    format!(
        "TypeRole({family}, {}, {}, {}, {}, {}, {}, {case})",
        float(role.size),
        float(role.line_height),
        role.weight,
        float(role.tracking),
        role.tabular,
        role.slashed_zero,
    )
}

/// A Kotlin `Float` literal.
fn float(value: f32) -> String {
    format!("{value:?}f")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn colours_are_argb_literals() {
        let kotlin = kotlin_tokens().unwrap();
        assert!(kotlin.contains("val LIME = Color(0xFFC6F24E)"));
        assert!(kotlin.contains("val SCRIM = Color(0xB8000000)"));
        assert!(kotlin.contains("val TEXT_PRIMARY = Color(0xFFECE8E0)"));
    }

    #[test]
    fn phone_roles_replace_the_desktop_ones_once() {
        let kotlin = kotlin_tokens().unwrap();
        assert_eq!(kotlin.matches("val TYPE_DISPLAY =").count(), 1);
        assert!(
            kotlin.contains(&format!("val TYPE_DISPLAY = {}", role_literal(&type_::phone::TYPE_DISPLAY)))
        );
        assert!(kotlin.contains("val TYPE_PAGE_TITLE = TypeRole(TypeFamily.PIXEL, 22.0f, 28.0f"));
        assert!(kotlin.contains(
            "val TYPE_LABEL = TypeRole(TypeFamily.UI, 11.0f, 16.0f, 600, 0.66f, true, false, TypeCase.UPPER)"
        ));
    }

    #[test]
    fn sprites_carry_their_frames_and_kind() {
        let kotlin = kotlin_tokens().unwrap();
        assert!(
            kotlin.contains(
                "val EQ = Sprite(R.drawable.eq, 12, 12, listOf(120, 120, 120, 120, 120, 120), true)"
            )
        );
        assert!(kotlin.contains(
            "val ALBUM_PLACEHOLDER = Sprite(R.drawable.album_placeholder, 24, 24, listOf(0), false)"
        ));
    }

    #[test]
    fn every_brand_becomes_one_white_path() {
        let brands = brand_vectors().unwrap();
        let names: Vec<&str> = brands.iter().map(|(name, _)| name.as_str()).collect();
        assert_eq!(names, ["brand_github.xml", "brand_google.xml", "brand_discord.xml"]);
        for (_, xml) in &brands {
            // XML forbids a double hyphen inside a comment.
            let comment = xml.split("<!--").nth(1).and_then(|rest| rest.split("-->").next()).unwrap();
            assert!(!comment.contains("--"), "{comment}");
            assert_eq!(xml.matches("android:pathData=\"M").count(), 1, "{xml}");
            assert!(xml.contains("android:viewportWidth=\"24\""));
        }
    }

    #[test]
    fn floats_have_the_kotlin_suffix() {
        assert_eq!(float(2.0), "2.0f");
        assert_eq!(float(-0.32), "-0.32f");
    }
}
